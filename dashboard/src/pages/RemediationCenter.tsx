import React, { useState } from 'react';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { recommendationsApi } from '../lib/api';
import { useAuth } from '../contexts/AuthContext';
import { Permission } from '../types/api';
import { CheckCircle, ShieldCheck, ShieldAlert, Sliders } from 'lucide-react';

export const RemediationCenter: React.FC = () => {
  const queryClient = useQueryClient();
  const { hasPermission } = useAuth();
  const [filterPriority, setFilterPriority] = useState('');
  const [filterStatus, setFilterStatus] = useState('ALL'); // ALL, OPEN, RESOLVED

  // Fetch all recommendations
  const { data: recommendations, isLoading, refetch } = useQuery({
    queryKey: ['recommendations-all'],
    queryFn: recommendationsApi.getAllRecommendations,
  });

  // Resolve recommendation mutation
  const resolveMutation = useMutation({
    mutationFn: (recId: string) => recommendationsApi.resolveRecommendation(recId),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['recommendations-all'] });
      refetch();
    },
  });

  // Filter recommendations
  const filteredRecs = React.useMemo(() => {
    if (!recommendations) return [];

    return recommendations.filter(rec => {
      const matchesPriority = filterPriority ? rec.priority === filterPriority : true;
      
      let matchesStatus = true;
      if (filterStatus === 'OPEN') matchesStatus = !rec.resolved_at;
      if (filterStatus === 'RESOLVED') matchesStatus = !!rec.resolved_at;

      return matchesPriority && matchesStatus;
    });
  }, [recommendations, filterPriority, filterStatus]);

  const getPriorityStyles = (prio: string) => {
    switch (prio) {
      case 'Critical': return 'text-cyber-red border-cyber-red/40 bg-cyber-red/10 threat-pulse-red';
      case 'High': return 'text-cyber-amber border-cyber-amber/35 bg-cyber-amber/10';
      case 'Medium': return 'text-cyber-yellow border-cyber-yellow/20 bg-cyber-yellow/10';
      default: return 'text-cyber-green border-cyber-green/20 bg-cyber-green/10';
    }
  };

  return (
    <div className="flex flex-col gap-6 font-mono text-xs select-none">
      
      {/* Header Panel */}
      <div className="glass-panel border border-cyber-border p-4 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded bg-cyber-green/15 border border-cyber-green/35 flex items-center justify-center">
            <ShieldAlert className="w-5 h-5 text-cyber-green animate-pulse" />
          </div>
          <div>
            <h2 className="font-bold text-gray-200 text-sm tracking-wider uppercase">AI_REMEDIATION_COMMAND_CENTER</h2>
            <div className="text-[10px] text-gray-400 mt-0.5">
              Automated mitigations and patches generated by SentinelAPI Machine Learning risk scoring engines.
            </div>
          </div>
        </div>
      </div>

      {/* Toolbar Filter */}
      <div className="glass-panel border border-cyber-border p-4 flex flex-col md:flex-row items-center justify-between gap-3">
        <div className="flex items-center gap-2">
          <Sliders className="w-4 h-4 text-cyber-cyan" />
          <span>FILTER_RECOMMENDATIONS:</span>
        </div>

        <div className="flex flex-wrap items-center gap-3 w-full md:w-auto">
          {/* Priority filter */}
          <select
            value={filterPriority}
            onChange={(e) => setFilterPriority(e.target.value)}
            className="bg-black/30 border border-cyber-border rounded px-2.5 py-1.5 text-xs text-gray-300 focus:outline-none focus:border-cyber-cyan w-full sm:w-40"
          >
            <option value="">ALL PRIORITIES</option>
            <option value="Critical">CRITICAL ONLY</option>
            <option value="High">HIGH AND CRITICAL</option>
            <option value="Medium">MEDIUM PRIORITY</option>
            <option value="Low">LOW PRIORITY</option>
          </select>

          {/* Status filter buttons */}
          <div className="flex border border-cyber-border rounded overflow-hidden">
            {(['ALL', 'OPEN', 'RESOLVED'] as const).map((status) => (
              <button
                key={status}
                onClick={() => setFilterStatus(status)}
                className={`px-3 py-1.5 font-bold transition-all cursor-pointer ${
                  filterStatus === status ? 'bg-cyber-cyan/15 text-cyber-cyan border-r border-cyber-cyan/35' : 'text-gray-500 hover:text-white hover:bg-white/5 border-r border-cyber-border/40'
                } last:border-r-0`}
              >
                {status}
              </button>
            ))}
          </div>
        </div>
      </div>

      {/* Tickets List */}
      {isLoading ? (
        <div className="min-h-[300px] flex flex-col items-center justify-center gap-3">
          <div className="w-8 h-8 rounded-full border-4 border-cyber-border border-t-cyber-cyan animate-spin" />
          <span className="text-[10px] text-cyber-cyan animate-pulse">PULLING AI RECOMMENDATIONS BUFFER...</span>
        </div>
      ) : filteredRecs.length === 0 ? (
        <div className="glass-panel border border-cyber-border p-12 text-center text-gray-500 italic flex flex-col items-center gap-2 bg-cyber-panel/10">
          <ShieldCheck className="w-12 h-12 text-cyber-green animate-bounce" />
          <div>
            <p className="font-bold text-gray-300 uppercase tracking-widest text-sm">NO VULNERABILITY TICKETS FOUND</p>
            <p className="text-[10px] text-gray-500 font-sans mt-1 max-w-sm mx-auto leading-normal">
              All tested bank microservice routes have resolved risk indexes under compliant thresholds.
            </p>
          </div>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
          {filteredRecs.map((rec) => {
            const isResolved = !!rec.resolved_at;
            return (
              <div
                key={rec.id}
                className={`glass-panel border p-4 flex flex-col gap-4 justify-between transition-all ${
                  isResolved ? 'border-cyber-border opacity-70' : 'border-cyber-border-hover/60 hover:border-cyber-cyan/40 shadow-[0_0_15px_rgba(6,182,212,0.03)]'
                }`}
              >
                <div className="flex flex-col gap-2.5">
                  
                  {/* Card top */}
                  <div className="flex justify-between items-center pb-2 border-b border-cyber-border/30">
                    <span className={`px-2 py-0.5 rounded text-[9px] font-bold border ${getPriorityStyles(rec.priority)}`}>
                      {rec.priority.toUpperCase()}
                    </span>
                    <span className="text-gray-500 text-[10px]" title={rec.trigger_rule}>
                      Rule: {rec.trigger_rule}
                    </span>
                  </div>

                  {/* Endpoint ID */}
                  <div className="flex items-center gap-1.5 mt-1">
                    <span className="w-1.5 h-1.5 rounded-full bg-cyber-cyan" />
                    <code className="text-cyber-cyan bg-black/45 px-1.5 py-0.5 rounded border border-white/5 font-semibold text-[10px] truncate max-w-[200px]" title={rec.endpoint_id}>
                      {rec.endpoint_id}
                    </code>
                  </div>

                  {/* Summary */}
                  <p className="text-[11px] text-gray-300 leading-relaxed font-sans">{rec.summary_text}</p>
                </div>

                {/* Resolving action trigger */}
                <div className="border-t border-cyber-border/30 pt-3.5">
                  {isResolved ? (
                    <div className="text-[10px] text-cyber-green bg-cyber-green/10 border border-cyber-green/20 px-2 py-1.5 rounded flex items-center gap-1.5 font-bold uppercase">
                      <CheckCircle className="w-4 h-4 text-cyber-green shrink-0" />
                      <span>RESOLVED BY {rec.resolved_by?.toUpperCase()}</span>
                    </div>
                  ) : (
                    hasPermission(Permission.RESOLVE_REMEDIATION) ? (
                      <button
                        onClick={() => resolveMutation.mutate(rec.id)}
                        disabled={resolveMutation.isPending}
                        className="w-full bg-cyber-green/15 hover:bg-cyber-green/35 border border-cyber-green/45 hover:border-cyber-green text-cyber-green hover:text-white transition-all py-1.5 rounded font-bold cursor-pointer disabled:opacity-40"
                      >
                        {resolveMutation.isPending ? 'DEPLOYING PATCH...' : 'APPLY AI PATCH CONFIG'}
                      </button>
                    ) : (
                      <div className="text-[10px] text-cyber-red/50 italic border border-cyber-red/20 bg-cyber-red/5 p-1.5 rounded text-center leading-normal">
                        Requires SEC_ADMIN clearance to apply patches
                      </div>
                    )
                  )}
                </div>

              </div>
            );
          })}
        </div>
      )}

    </div>
  );
};
